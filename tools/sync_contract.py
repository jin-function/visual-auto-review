"""Generate the extension contract from the app's canonical, packaged contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def schema() -> str:
    c = json.loads((ROOT / "app/review-contract.json").read_text(encoding="utf-8"))
    value = {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "VisualQA Chrome review bundle", "type": "object",
        "required": ["format", "version", "packageId", "coordinateSpace", "runId", "url", "responsive", "targets"],
        "properties": {"format": {"const": c["format"]}, "version": {"const": c["version"]},
            "packageId": {"type": "string", "pattern": "^[a-f0-9]{64}$"}, "coordinateSpace": {"const": c["coordinateSpace"]},
            "runId": {"type": "string", "minLength": 1}, "url": {"type": "string", "format": "uri"},
            "responsive": {"type": "object", "required": ["breakpoint"], "properties": {"breakpoint": {"type": "integer", "minimum": 320, "maximum": 4096}}},
            "targets": {"type": "array", "minItems": 1, "maxItems": c["maxTargets"], "items": {"type": "object",
                "required": ["device", "targetId", "revisionId", "runId", "url", "imageRole", "viewportWidth", "placement", "display", "image", "findings"],
                "properties": {"device": {"enum": c["devices"]}, "imageRole": {"const": "reference-original"},
                    "findings": {"type": "array", "maxItems": c["maxFindings"]},
                    "image": {"type": "object", "required": ["mime", "width", "height", "sha256", "base64"],
                        "properties": {"mime": {"const": "image/png"}, "sha256": {"type": "string", "pattern": "^[a-f0-9]{64}$"},
                            "base64": {"type": "string", "maxLength": ((c["maxImageBytes"] + 2) // 3) * 4},
                            "width": {"type": "integer", "minimum": 1, "maximum": 32768}, "height": {"type": "integer", "minimum": 1, "maximum": 150000}}}}}}}}
    return json.dumps(value, ensure_ascii=False, indent=4) + "\n"


def generated() -> str:
    contract = json.loads((ROOT / "app/review-contract.json").read_text(encoding="utf-8"))
    return "// Generated by tools/sync_contract.py. Edit app/review-contract.json.\nexport const CONTRACT = Object.freeze(" + json.dumps(contract, ensure_ascii=False, indent=4) + ");\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {ROOT / "chrome-extension/contract.mjs": generated(), ROOT / "schema/review-package.schema.json": schema()}
    for destination, expected in outputs.items():
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != expected:
                raise SystemExit("앱과 확장의 검수 파일 규격이 다릅니다. tools/sync_contract.py를 실행하세요.")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(expected, encoding="utf-8")
